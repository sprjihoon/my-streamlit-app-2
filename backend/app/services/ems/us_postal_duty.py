def lookup_us_postal_rate(hs_code: str) -> tuple[float | None, str]:
    digits = re.sub(r"\D", "", hs_code or "")
    best = ""
    for key in _RATES:
        if digits.startswith(key) and len(key) > len(best):
            best = key
    if not best:
        if not digits:
            return None, "HS 없음"
        return None, "세율표에 없음"
    rate, label = _RATES[best]
    return rate, label
